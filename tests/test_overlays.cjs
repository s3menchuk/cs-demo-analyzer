const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const sandbox={Path2D:class {constructor(path){this.path=path;}}};
vm.runInNewContext(fs.readFileSync('static/replay.js','utf8')+';globalThis.r=Replay;',sandbox);
vm.runInNewContext(fs.readFileSync('static/map-view.js','utf8'),sandbox);
vm.runInNewContext(fs.readFileSync('static/overlays.js','utf8')+';globalThis.o=Overlays;',sandbox);
const o=sandbox.o,r=sandbox.r;
assert.equal(o.vector(0).x,1);
assert.ok(Math.abs(o.vector(90).y-1)<1e-9);
assert.ok(Math.abs(o.vector(-90).y+1)<1e-9);
assert.ok(Math.abs(Math.abs(r.angle(179,-179,.5))-180)<1e-9);
assert.ok(Math.abs(Math.abs(r.angle(-179,179,.5))-180)<1e-9);
assert.equal(r.angle(0,90,.5),45);
const track={start:100,end:108,owner_id:'1',side:'CT',points:[{tick:100,x:0,y:0,z:0},{tick:104,x:10,y:0,z:0},{tick:108,x:20,y:0,z:0}]};
assert.equal(o.position(track,99),null);
assert.equal(o.position(track,109),null);
assert.equal(o.position(track,102).x,5);
assert.equal(o.position(track,102,false).x,0);
assert.equal(o.matches(track,'1','CT'),true);
assert.equal(o.matches(track,'2','CT'),false);
assert.equal(o.matches(track,'','T'),false);
let strokes=[];
const context=new Proxy({moveTo:(x,y)=>strokes.push([x,y]),lineTo:(x,y)=>strokes.push([x,y])},{get:(obj,key)=>obj[key]||(()=>{})});
o.draw(context,p=>[p.x,p.y],null,'default',[{...track,kind:'he'}],[],102,64,{owner:'',side:'',trails:true,interpolate:false});
assert.ok(strokes.every(p=>p[0]<=0),'Trail must not show future positions');
const counts=o.draw(context,p=>[p.x,p.y],null,'default',[],[{kind:'smoke',start:100,end:200,x:0,y:0,z:0}],200,64,{});
assert.equal(counts.active,0);
console.log('View angles, grenade playback, filters, expiry and no-future trails checks passed');
