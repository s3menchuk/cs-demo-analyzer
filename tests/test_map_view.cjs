const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const sandbox = {};
vm.runInNewContext(fs.readFileSync('static/map-view.js','utf8')+';globalThis.view=MapView;',sandbox);
const view=sandbox.view;
const catalog=JSON.parse(fs.readFileSync('static/maps/manifest.json','utf8'));
const ctx=new Proxy({}, {get:(obj,key)=>obj[key] || (()=>{})});
const canvas={width:900,height:900,getContext:()=>ctx};
const mirage=catalog.de_mirage;
view.images.set(mirage.levels[0].image,{});
const {project,calibrated}=view.base(canvas,mirage,'default',[]);
assert.equal(calibrated,true);
assert.deepEqual(Array.from(project({x:-3230,y:1713})),[0,0]);
assert.deepEqual(Array.from(project({x:1890,y:-3407})),[900,900]);
assert.deepEqual(Array.from(project({x:-670,y:-847})),[450,450]);
assert.equal(view.level(catalog.de_nuke,-496),'lower');
assert.equal(view.level(catalog.de_nuke,-495),'default');
assert.equal(view.onLevel(catalog.de_nuke,{z:-600},'default'),false);
const fallback=view.base(canvas,null,'default',[{x:0,y:0},{x:100,y:100}]);
const a=fallback.project({x:0,y:0}),b=fallback.project({x:100,y:100});
assert.equal(b[0]-a[0],a[1]-b[1]);
console.log('Map projection and floor checks passed');
