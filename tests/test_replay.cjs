const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const sandbox={};
vm.runInNewContext(fs.readFileSync('static/replay.js','utf8')+';globalThis.replay=Replay;',sandbox);
const replay=sandbox.replay;
const player=(x,extra={})=>({id:'1',side:'CT',x,y:0,z:0,alive:true,hp:100,...extra});
const frame=(tick,x,extra={})=>({tick,round:1,players:[player(x,extra)]});
const frames=[frame(100,0),frame(104,10),frame(108,20)];
assert.equal(replay.index(frames,104),1);
assert.equal(replay.index(frames,103),0);
assert.equal(replay.index(frames,200),2);
assert.equal(replay.index(frames,50),0);
assert.equal(replay.snapshot(frames,102).players[0].x,5);
assert.equal(replay.snapshot(frames,102,64,false).players[0].x,0);
assert.equal(replay.snapshot(frames,104).players[0].x,10);
assert.equal(replay.snapshot(frames,200).players[0].x,20);
assert.equal(replay.snapshot([],0),null);
assert.equal(replay.snapshot([frame(0,0),frame(4,10,{alive:false,hp:0})],2).players[0].alive,true);
assert.equal(replay.snapshot([frame(0,0),frame(4,10,{alive:false,hp:0})],4).players[0].alive,false);
assert.equal(replay.snapshot([frame(0,0),frame(4,1000)],2).players[0].x,0);
assert.equal(replay.snapshot([frame(0,0),frame(4,10,{z:-600})],2).players[0].z,0);
assert.equal(replay.snapshot([frame(0,0),frame(200,50)],100).players[0].x,0);
assert.equal(replay.sampleRate({sample_seconds:1}),1); // Old saved matches.
assert.equal(replay.sampleRate({sample_seconds:1/16}),16);
assert.equal(replay.sampleRate({sample_rate:64}),64);
assert.equal(replay.tickAt(100,1000,1,64,1000),164);
assert.equal(replay.tickAt(100,1000,4,64,1000),356);
assert.equal(replay.tickAt(100,100000,4,64,1000),1000);
assert.equal(replay.formatTime(61.0625),'1:01.062');
assert.deepEqual(JSON.parse(JSON.stringify(replay.bounds(frames))),[{x:0,y:0},{x:20,y:0}]);
console.log('Replay timing, interpolation, discontinuity and legacy sampling checks passed');
