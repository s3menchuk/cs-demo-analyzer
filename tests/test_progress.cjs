const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('static/app.js','utf8');
const elements=Object.fromEntries(['#uploadBatch','#batchTitle','#batchFiles','#cancelUploads'].map(id=>[id,{}]));
const context=vm.createContext({uploading:false,uploadCancelled:false,batchItems:[{id:'a',name:'match.dem',state:'accepted'}],libraryMatches:[], $:id=>elements[id],esc:s=>String(s).replaceAll('<','&lt;')});
vm.runInContext(source.slice(source.indexOf('function progressBar('),source.indexOf('async function library()')),context);
context.libraryMatches=[{id:'a',status:'parsing',progress:45,stage:'Positions'}];
vm.runInContext('renderBatch()',context);
assert.match(elements['#batchFiles'].innerHTML,/value="45"/);
assert.match(elements['#batchFiles'].innerHTML,/Positions/);
context.libraryMatches[0].status='ready';
vm.runInContext('renderBatch()',context);
assert.match(elements['#batchFiles'].innerHTML,/value="100"/);
context.libraryMatches[0].status='error';
context.libraryMatches[0].error='<failure>';
vm.runInContext('renderBatch()',context);
assert.match(elements['#batchFiles'].innerHTML,/&lt;failure>/);
assert.doesNotMatch(elements['#batchFiles'].innerHTML,/<progress/);
context.batchItems=[];
context.libraryMatches=[{id:'b',name:'restored.dem',status:'parsing',progress:68,stage:'Grenades'}];
vm.runInContext('renderBatch()',context);
assert.equal(elements['#uploadBatch'].hidden,false);
assert.match(elements['#batchFiles'].innerHTML,/value="68"/);
context.libraryMatches[0].status='ready';
vm.runInContext('renderBatch()',context);
assert.match(elements['#batchFiles'].innerHTML,/value="100"/);
assert.equal(elements['#cancelUploads'].hidden,true);
console.log('Analysis progress, completion, errors and reload: OK');
